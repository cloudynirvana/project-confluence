"""
Neural Therapy Brain — Project Confluence
=========================================

A compact recurrent neural controller (a "small brain") whose *neurons are
trained on therapy datasets* to keep the complex cancer environment under
therapeutic control — suppressing the resistant clone and holding tumour
burden near a healthy attractor — **despite ambivalent externalities**
(biological uncertainty, measurement noise, and inter-patient variability).

Where the hand-crafted ``AdaptiveController`` encodes a fixed policy
π(state) → dose, this module *learns* that policy with a recurrent network:

    observation history ──► GRU "brain" ──► raw dose ──► SAFETY LAYER ──► dose

The safety layer is the same non-overridable "assurance layer" used by
``AdaptiveController`` (absolute dose cap, forced drug holidays, cumulative
toxicity budget, Nigeria NSTG 2022 layer), so a learned policy can never
violate the hard clinical bounds.

────────────────────────────────────────────────────────────────────────────
DATA & VALIDATION DISCLAIMER
────────────────────────────────────────────────────────────────────────────
By default the brain is trained on **synthetic** trajectories generated by the
repository's mechanistic clonal-dynamics simulator under the robust adaptive
expert policy. Real longitudinal clinical datasets can be plugged in via
``TherapyDataset.from_real_cohort`` — but real-data training is **pending** and
MUST be subject to independent expert review and authentic clinical validation
before any translational interpretation. This is a research artifact only, not
a medical device or clinical decision-support tool. See ``DISCLAIMER.md``.
"""

