# Number of scalar features fed to the brain at each timestep.
OBS_DIM = 6


# ═══════════════════════════════════════════════════════════════════════════
# OBSERVATION ENCODING
# ═══════════════════════════════════════════════════════════════════════════

def encode_observation(
    sensitive: float,
    resistant: float,
    carrying_capacity: float,
    efficacy: float,
    toxicity_fraction: float,
    is_dosing: bool,
    last_dose: float,
) -> List[float]:
    """Map the raw biological + controller state to the brain's input vector.

    All features are kept in roughly ``[0, 1]`` so the network sees a
    well-conditioned input without an external scaler.
    """
    total = sensitive + resistant
    v_frac = total / carrying_capacity if carrying_capacity > 0 else 0.0
    r_frac = resistant / total if total > 1e-10 else 0.0
    return [
        float(np.clip(v_frac, 0.0, 2.0)),
        float(np.clip(r_frac, 0.0, 1.0)),
        float(np.clip(efficacy, 0.0, 1.0)),
        float(np.clip(toxicity_fraction, 0.0, 1.5)),
        1.0 if is_dosing else 0.0,
        float(np.clip(last_dose, 0.0, 1.0)),
    ]


# ═══════════════════════════════════════════════════════════════════════════
# THE BRAIN (recurrent policy network)
# ═══════════════════════════════════════════════════════════════════════════

class NeuralTherapyBrain(nn.Module):
    """A small GRU-based recurrent dosing policy.

    Intentionally compact (a "fly brain"): a single-layer GRU plus a linear
    read-out head. The recurrent hidden state gives the controller memory of
    the trajectory so far, which is what lets it react to *trends* (e.g. a
    rising resistant fraction) rather than only the instantaneous state.

    Output is squashed to ``[0, max_dose]`` so the raw network action already
    respects the absolute dose cap before the safety layer runs.
    """

    def __init__(
        self,
        obs_dim: int = OBS_DIM,
        hidden_dim: int = 32,
        max_dose: float = 0.9,
    ):
        if not TORCH_AVAILABLE:
            raise ImportError(
                "PyTorch is required for NeuralTherapyBrain. Install it with "
                "`pip install torch` (CPU build is sufficient)."
            )
        super().__init__()
        self.obs_dim = obs_dim
        self.hidden_dim = hidden_dim
        self.max_dose = float(max_dose)
        self.gru = nn.GRUCell(obs_dim, hidden_dim)
        self.head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.Tanh(),
            nn.Linear(hidden_dim, 1),
        )

    # -- sequence forward (training) ----------------------------------------
    def forward(self, obs_seq: "torch.Tensor") -> "torch.Tensor":
        """Run the brain over a batch of observation sequences.

        Args:
            obs_seq: ``[batch, seq_len, obs_dim]``.

        Returns:
            doses: ``[batch, seq_len]`` in ``[0, max_dose]``.
        """
        batch, seq_len, _ = obs_seq.shape
        h = torch.zeros(batch, self.hidden_dim, dtype=obs_seq.dtype, device=obs_seq.device)
        outputs = []
        for t in range(seq_len):
            h = self.gru(obs_seq[:, t, :], h)
            outputs.append(self.head(h))
        doses = torch.sigmoid(torch.stack(outputs, dim=1).squeeze(-1)) * self.max_dose
        return doses

    # -- single step (online closed-loop deployment) ------------------------
    def step(
        self,
        obs: List[float],
        hidden: Optional["torch.Tensor"] = None,
    ) -> Tuple[float, "torch.Tensor"]:
        """Advance the brain one timestep, carrying its recurrent memory."""
        with torch.no_grad():
            x = torch.tensor(obs, dtype=torch.float32).unsqueeze(0)
            if hidden is None:
                hidden = torch.zeros(1, self.hidden_dim, dtype=torch.float32)
            hidden = self.gru(x, hidden)
            raw = torch.sigmoid(self.head(hidden)).item() * self.max_dose
        return float(raw), hidden


